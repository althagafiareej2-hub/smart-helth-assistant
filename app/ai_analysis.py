def extract_duration(text):

    duration_patterns = [

        (r"منذ\s+يومين", "يومان"),
        (r"لي\s+يومين", "يومان"),
        (r"من\s+يومين", "يومان"),

        (r"منذ\s+ثلاثة\s+ايام", "3 أيام"),
        (r"منذ\s+ثلاث\s+ايام", "3 أيام"),
        (r"لي\s+ثلاثة\s+ايام", "3 أيام"),

        (r"منذ\s+اربعة\s+ايام", "4 أيام"),
        (r"منذ\s+خمسة\s+ايام", "5 أيام"),

        (r"منذ\s+اسبوع", "أسبوع"),
        (r"لي\s+اسبوع", "أسبوع"),
        (r"من\s+اسبوع", "أسبوع"),

        (r"منذ\s+اسبوعين", "أسبوعان"),
        (r"لي\s+اسبوعين", "أسبوعان"),

        (r"منذ\s+شهر", "شهر"),
        (r"لي\s+شهر", "شهر")
    ]


    for pattern, result in duration_patterns:

        if re.search(pattern, text):

            return result


    numeric_patterns = [

        r"منذ\s+(\d+)\s*(يوم|ايام|اسبوع|اسابيع|شهر|اشهر)",

        r"من\s+(\d+)\s*(يوم|ايام|اسبوع|اسابيع|شهر|اشهر)",

        r"لي\s+(\d+)\s*(يوم|ايام|اسبوع|اسابيع|شهر|اشهر)"
    ]


    for pattern in numeric_patterns:

        match = re.search(
            pattern,
            text
        )

        if match:

            return (
                f"{match.group(1)} "
                f"{match.group(2)}"
            )


    if "اليوم" in text:

        return "اليوم"


    if "امس" in text:

        return "منذ يوم تقريبًا"


    return "غير محددة"


