def extract_duration(text):
    for p,r in [(r'منذ\s+يومين','يومان'),(r'لي\s+يومين','يومان'),(r'منذ\s+ثلاثة\s+ايام','3 أيام'),(r'منذ\s+اسبوع','أسبوع'),(r'لي\s+اسبوع','أسبوع'),(r'منذ\s+اسبوعين','أسبوعان'),(r'منذ\s+شهر','شهر')]:
        if re.search(p,text): return r
    m=re.search(r'(?:منذ|من|لي)\s+(\d+)\s*(يوم|ايام|اسبوع|اسابيع|شهر|اشهر)',text)
    if m:return f'{m.group(1)} {m.group(2)}'
    if 'اليوم' in text:return 'اليوم'
    if 'امس' in text:return 'منذ يوم تقريبًا'
    return 'غير محددة'

def extract_severity(text):
    if any(x in text for x in ['شديد جدا','شديدة جدا','شديد','شديدة','قوي جدا','قوية جدا','غير محتمل','ما اقدر','لا استطيع','صعب جدا']): return 'شديدة'
    if any(x in text for x in ['متوسط','متوسطة','متوسطه','متوسطا']): return 'متوسطة'
    if any(x in text for x in ['خفيف','خفيفة','بسيط','بسيطة']): return 'خفيفة'
    return 'غير محددة'

def analyze_symptoms(text):
    if not text.strip(): return {'detected_symptoms':[],'duration':'غير محددة','severity':'غير محددة','priority':'unknown','doctor_summary':'لم يتم إدخال وصف للأعراض.','note':'هذه النتيجة للمساندة ولا تُعد تشخيصًا طبيًا.'}
    t=normalize_text(text); symptoms=extract_symptoms(t); duration=extract_duration(t); severity=extract_severity(t)
    high=['ضيق التنفس','ضيق نفس','صعوبه التنفس','صعوبه في التنفس','الم الصدر','الم في الصدر','فقدت الوعي','اغمى علي','نزيف شديد']
    priority='high' if any(x in t for x in high) else ('medium' if len(symptoms)>=2 else 'low')
    p={'high':'عالية','medium':'متوسطة','low':'منخفضة','unknown':'غير محددة'}[priority]
    st='، '.join(symptoms) if symptoms else 'لم يتم التعرف على أعراض محددة'
    summary=f'الأعراض المرصودة: {st}. مدة الأعراض: {duration}. الشدة المذكورة: {severity}. الأولوية المقترحة: {p}. يوصى بالتقييم السريري من قبل الطبيب.'
    return {'detected_symptoms':symptoms,'duration':duration,'severity':severity,'priority':priority,'doctor_summary':summary,'note':'هذه النتيجة للمساندة ولا تُعد تشخيصًا طبيًا.'}
