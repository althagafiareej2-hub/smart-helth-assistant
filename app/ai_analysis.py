# =========================================================

def extract_severity(text):

    high_words = [

        "شديد جدا",
        "شديدة جدا",

        "شديد",
        "شديدة",

        "قوي جدا",
        "قوية جدا",

        "غير محتمل",

        "ما اقدر",
        "لا استطيع",

        "صعب جدا"
    ]


    medium_words = [

        "متوسط",
        "متوسطة",
        "متوسطه",
        "متوسطا"
    ]


    mild_words = [

        "خفيف",
        "خفيفة",

        "بسيط",
        "بسيطة"
    ]


    if any(
        word in text
        for word in high_words
    ):

        return "شديدة"


    if any(
        word in text
        for word in medium_words
    ):

        return "متوسطة"


    if any(
        word in text
        for word in mild_words
    ):

        return "خفيفة"


    return "غير محددة"


# =========================================================
# تحديد الأولوية
# =========================================================

def calculate_priority(text, symptoms):

    # حالات طارئة للتجربة
    emergency_patterns = [

        "ضيق التنفس",
        "ضيق نفس",

        "صعوبه التنفس",
        "صعوبه في التنفس",

        "الم الصدر",
        "الم في الصدر",

        "فقدت الوعي",
        "اغمى علي",

        "نزيف شديد"
    ]


    if any(
        pattern in text
        for pattern in emergency_patterns
    ):

        return "high"


    # أربع أعراض أو أكثر
    if len(symptoms) >= 4:

        return "medium"


    # ثلاث أعراض أو أكثر مع حرارة
    if (
        len(symptoms) >= 3
        and "حمى" in symptoms
    ):

        return "medium"


    # عرضين أو أكثر
    if len(symptoms) >= 2:

        return "medium"


    return "low"


# =========================================================
# إنشاء ملخص للطبيب
# =========================================================

def create_doctor_summary(
    symptoms,
    duration,
    severity,
    priority
):

    if symptoms:

        symptoms_text = "، ".join(
            symptoms
        )

    else:

        symptoms_text = (
            "لم يتم التعرف على أعراض محددة"
        )


    priority_text = {

        "high": "عالية",

        "medium": "متوسطة",

        "low": "منخفضة",

        "unknown": "غير محددة"

    }.get(
        priority,
        "غير محددة"
    )


    return (

        f"الأعراض المرصودة: {symptoms_text}. "

        f"مدة الأعراض: {duration}. "

        f"الشدة المذكورة: {severity}. "

        f"الأولوية المقترحة: {priority_text}. "

        "يوصى بالتقييم السريري من قبل الطبيب."
    )
