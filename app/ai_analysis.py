# =========================================================
# استخراج مدة الأعراض
# =========================================================

def extract_duration(text):

    patterns = [
        (r'منذ\s+يومين', 'يومان'),
        (r'لي\s+يومين', 'يومان'),
        (r'منذ\s+ثلاثة\s+ايام', '3 أيام'),
        (r'منذ\s+ثلاث\s+ايام', '3 أيام'),
        (r'منذ\s+اسبوع', 'أسبوع'),
        (r'لي\s+اسبوع', 'أسبوع'),
        (r'منذ\s+اسبوعين', 'أسبوعان'),
        (r'منذ\s+شهر', 'شهر'),
        (r'منذ\s+ساعه', 'ساعة'),
        (r'منذ\s+ساعة', 'ساعة')
    ]

    for pattern, result in patterns:
        if re.search(pattern, text):
            return result

    match = re.search(
        r'(?:منذ|من|لي)\s+(\d+)\s*'
        r'(يوم|ايام|اسبوع|اسابيع|شهر|اشهر|ساعه|ساعات)',
        text
    )

    if match:
        return f'{match.group(1)} {match.group(2)}'

    if 'اليوم' in text:
        return 'اليوم'

    if 'امس' in text:
        return 'منذ يوم تقريبًا'

    return 'غير محددة'


# =========================================================
# استخراج شدة الأعراض
# =========================================================

def extract_severity(text):

    if any(x in text for x in [
        'شديد جدا',
        'شديدة جدا',
        'شديد',
        'شديدة',
        'قوي جدا',
        'قوية جدا',
        'غير محتمل',
        'ما اقدر',
        'لا استطيع',
        'صعب جدا'
    ]):
        return 'شديدة'

    if any(x in text for x in [
        'متوسط',
        'متوسطة',
        'متوسطه',
        'متوسطا'
    ]):
        return 'متوسطة'

    if any(x in text for x in [
        'خفيف',
        'خفيفة',
        'بسيط',
        'بسيطة'
    ]):
        return 'خفيفة'

    return 'غير محددة'


# =========================================================
# تحديد علامات الخطر
# =========================================================

def detect_danger_signs(text):

    danger_signs = []

    if any(x in text for x in [
        'ضيق التنفس',
        'ضيق نفس',
        'صعوبه التنفس',
        'صعوبه في التنفس',
        'ما اقدر اتنفس',
        'صعب اتنفس'
    ]):
        danger_signs.append('ضيق في التنفس')

    if any(x in text for x in [
        'الم الصدر',
        'الم في الصدر',
        'وجع الصدر',
        'وجع في الصدر',
        'صدري يؤلمني',
        'صدري يوجعني'
    ]):
        danger_signs.append('ألم في الصدر')

    if any(x in text for x in [
        'نزيف شديد',
        'ينزف كثيرا',
        'نزيف قوي'
    ]):
        danger_signs.append('نزيف شديد')

    if any(x in text for x in [
        'فقدت الوعي',
        'اغمى علي',
        'اغماء'
    ]):
        danger_signs.append('فقدان الوعي')

    return danger_signs


# =========================================================
# تحديد المسار المقترح
# =========================================================

def determine_path(priority):

    if priority == 'high':
        return (
            'مسار عاجل: يوصى بطلب المساعدة الطبية العاجلة '
            'وعدم الاكتفاء بالرعاية الذاتية.'
        )

    if priority == 'medium':
        return (
            'مسار المتابعة الطبية: يوصى باستشارة الطبيب '
            'إذا استمرت الأعراض أو ازدادت شدتها.'
        )

    return (
        'مسار الرعاية الذاتية والمتابعة: الراحة ومراقبة الأعراض، '
        'مع استشارة الطبيب عند استمرارها أو تفاقمها.'
    )


# =========================================================
# تحليل الحالة
# =========================================================

def analyze_symptoms(text):

    if not text or not text.strip():

        return {
            'age': None,
            'gender': 'غير محدد',
            'detected_symptoms': [],
            'duration': 'غير محددة',
            'associated_symptoms': [],
            'danger_signs': [],
            'severity': 'غير محددة',
            'priority': 'unknown',
            'priority_ar': 'غير محددة',
            'recommended_path': 'لا يمكن تحديد المسار قبل إدخال البيانات.',
            'doctor_summary': 'لم يتم إدخال وصف للحالة.',
            'note': 'هذه النتيجة للدراسة والمساندة ولا تُعد تشخيصًا طبيًا.'
        }

    text = normalize_text(text)

    age = extract_age(text)
    gender = extract_gender(text)
    symptoms = extract_symptoms(text)
    duration = extract_duration(text)
    severity = extract_severity(text)
    danger_signs = detect_danger_signs(text)

    # =====================================================
    # تحديد الأعراض المصاحبة
    # =====================================================

    associated_symptoms = []

    if len(symptoms) > 1:
        associated_symptoms = symptoms[1:]

    # =====================================================
    # تحديد مستوى الأولوية
    # =====================================================

    if danger_signs:
        priority = 'high'
        priority_ar = 'عالية'

    elif len(symptoms) >= 2:
        priority = 'medium'
        priority_ar = 'متوسطة'

    else:
        priority = 'low'
        priority_ar = 'منخفضة'

    # =====================================================
    # المسار المقترح
    # =====================================================

    recommended_path = determine_path(priority)

    # =====================================================
    # تجهيز النص النهائي
    # =====================================================

    symptoms_text = (
        '، '.join(symptoms)
        if symptoms
        else 'لم يتم التعرف على أعراض محددة'
    )

    associated_text = (
        '، '.join(associated_symptoms)
        if associated_symptoms
        else 'لا توجد أعراض مصاحبة محددة'
    )

    danger_text = (
        '، '.join(danger_signs)
        if danger_signs
        else 'لا توجد علامات خطر واضحة'
    )

    age_text = (
        str(age)
        if age is not None
        else 'غير محدد'
    )

    summary = (
        f'العمر: {age_text}. '
        f'الجنس: {gender}. '
        f'الأعراض: {symptoms_text}. '
        f'المدة: {duration}. '
        f'الأعراض المصاحبة: {associated_text}. '
        f'علامات الخطر: {danger_text}. '
        f'مستوى الأولوية: {priority_ar}. '
        f'المسار المقترح: {recommended_path}'
    )

    return {

        'age': age,

        'gender': gender,

        'detected_symptoms': symptoms,

        'duration': duration,

        'associated_symptoms': associated_symptoms,

        'danger_signs': danger_signs,

        'severity': severity,

        'priority': priority,

        'priority_ar': priority_ar,

        'recommended_path': recommended_path,

        'doctor_summary': summary,

        'note': (
            'هذه النتيجة مخصصة للدراسة واختبار الموقع '
            'ولا تُعد تشخيصًا طبيًا.'
        )
    }
